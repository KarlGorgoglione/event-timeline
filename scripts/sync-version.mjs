// Writes each library's package.json version into its `src/version.ts`, so the
// `VERSION` export matches the published package. Runs after
// `changeset version` (see the root `version-packages` script); a unit test in
// each package fails if the two ever drift.

import { readFileSync, writeFileSync } from 'node:fs';

for (const pkg of ['core']) {
  const dir = new URL(`../packages/${pkg}/`, import.meta.url);
  const { version } = JSON.parse(
    readFileSync(new URL('package.json', dir), 'utf8'),
  );
  writeFileSync(
    new URL('src/version.ts', dir),
    `// Generated by scripts/sync-version.mjs from package.json; do not edit.\nexport const VERSION = '${version}';\n`,
  );
}
